/* Identifiants stables : matière-numéro du domaine-numéro de l'objectif. */
const COMPETENCES = [];
{
  const n = {};
  PROGRAMME.forEach(dom => {
    n[dom.m] = (n[dom.m] || 0) + 1;
    dom.items = dom.items.map((t, i) => {
      const c = { id: `${dom.m}-${n[dom.m]}-${i + 1}`, t, m: dom.m, d: dom.d };
      COMPETENCES.push(c);
      return c;
    });
  });
}
const COMP = id => COMPETENCES.find(c => c.id === id);
